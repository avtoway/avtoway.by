export function normalizeTaxiRequirements(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

export function validateTaxiRequirements(value: unknown, isTaxi: boolean): string | null {
  const text = normalizeTaxiRequirements(value);
  if (isTaxi && !text) return "Заполните требования к водителю такси";
  if (text.length > TAXI_REQUIREMENTS_MAX_LENGTH) {
    return `Текст требований не должен превышать ${TAXI_REQUIREMENTS_MAX_LENGTH} символов`;
  }
  return null;
}
