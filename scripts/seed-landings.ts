async function main() {
  const db = getPrismaClient();
  for (const landing of landings) {
    await db.serviceLanding.upsert({
      where: { slug: landing.slug },
      update: {
        seoTitle: landing.seoTitle,
        seoDescription: landing.seoDescription,
        ogTitle: landing.ogTitle,
        ogDescription: landing.ogDescription,
        content: JSON.stringify(landing.content),
        isActive: true,
      },
      create: {
        slug: landing.slug,
        seoTitle: landing.seoTitle,
        seoDescription: landing.seoDescription,
        ogTitle: landing.ogTitle,
        ogDescription: landing.ogDescription,
        content: JSON.stringify(landing.content),
        isActive: true,
      },
    });
    console.log(`landing seeded: ${landing.slug}`);
  }
}

main()
  .catch(error => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await getPrismaClient().$disconnect();
  });
