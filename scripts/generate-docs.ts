const pageBreak = () => new Paragraph({ children: [new TextRun({ text: "", break: 1 })] });

function cell(text: string, header = false): TableCell {
  return new TableCell({
    children: [
      new Paragraph({
        children: [new TextRun({ text, bold: header, color: header ? "FFFFFF" : undefined, size: 20 })],
        spacing: { before: 40, after: 40 },
      }),
    ],
    shading: header ? { type: ShadingType.CLEAR, fill: "C0392B", color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
  });
}

function table(headers: string[], rows: string[][]): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "DDDDDD" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "DDDDDD" },
      left: { style: BorderStyle.SINGLE, size: 4, color: "DDDDDD" },
      right: { style: BorderStyle.SINGLE, size: 4, color: "DDDDDD" },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: "EEEEEE" },
      insideVertical: { style: BorderStyle.SINGLE, size: 4, color: "EEEEEE" },
    },
    rows: [
      new TableRow({ tableHeader: true, children: headers.map(header => cell(header, true)) }),
      ...rows.map(row => new TableRow({ children: row.map(value => cell(value)) })),
    ],
  });
}

function img(file: string, width = 600): Paragraph {
  const data = shotCache.get(file);
  if (!data) {
    return muted(`Скриншот ${file} не найден. Запустите npm run docs:screenshots.`);
  }
  // Размеры PNG лежат в IHDR: ширина и высота по смещениям 16 и 20.
  const sourceWidth = data.readUInt32BE(16) || 1440;
  const sourceHeight = data.readUInt32BE(20) || 900;
  const height = Math.max(1, Math.round(width * (sourceHeight / sourceWidth)));
  return new Paragraph({
    children: [new ImageRun({ data, transformation: { width, height }, type: "png" })],
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 60 },
  });
}

function caption(text: string): Paragraph {
  return new Paragraph({
    children: [new TextRun({ text, italics: true, size: 18, color: "777777" })],
    alignment: AlignmentType.CENTER,
    spacing: { after: 180 },
  });
}

function figure(file: string, text: string, width = 600): Array<Paragraph> {
  return [img(file, width), caption(text)];
}

function coverBlock(title: string, subtitle: string): Paragraph[] {
  return [
    new Paragraph({
      children: [
        new TextRun({ text: "АВТО", bold: true, size: 56, color: "111111" }),
        new TextRun({ text: "WAY", bold: true, size: 56, color: "EF4444" }),
      ],
      alignment: AlignmentType.CENTER,
      spacing: { before: 900, after: 200 },
    }),
    new Paragraph({
      children: [new TextRun({ text: title, bold: true, size: 40 })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 160 },
    }),
    new Paragraph({
      children: [new TextRun({ text: subtitle, size: 24, color: "555555" })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 600 },
    }),
    new Paragraph({
      children: [new TextRun({ text: "Версия: ноябрь 2026", size: 20, color: "777777" })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 80 },
    }),
    new Paragraph({
      children: [new TextRun({ text: "Документ для владельца и сотрудников сайта", size: 20, color: "777777" })],
      alignment: AlignmentType.CENTER,
      spacing: { after: 900 },
    }),
    pageBreak(),
  ];
}

function doc(children: (Paragraph | Table)[], title: string): Document {
  return new Document({
    title,
    creator: BRAND,
    description: `Инструкция ${BRAND}`,
    styles: {
      default: {
        document: {
          run: { font: "Calibri", size: 22, color: "222222" },
          paragraph: { spacing: { line: 300 } },
        },
      },
    },
    numbering: {
      config: [
        {
          reference: "steps",
          levels: [
            {
              level: 0,
              format: "decimal",
              text: "%1.",
              alignment: AlignmentType.START,
              style: { paragraph: { indent: { left: 720, hanging: 360 } } },
            },
          ],
        },
      ],
    },
    sections: [{ properties: {}, children }],
  });
}

