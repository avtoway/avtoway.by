async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  try {
    const files = await readdir(SHOTS_DIR);
    for (const file of files) {
      if (!file.endsWith(".png")) continue;
      shotCache.set(file, await readFile(path.join(SHOTS_DIR, file)));
    }
    console.log(`Загружено скриншотов: ${shotCache.size}`);
  } catch {
    console.warn("Скриншоты не найдены. Документы будут без изображений.");
  }

  await buildAdminGuide();
  await buildSeoGuide();
  await buildAdsGuide();
  console.log(`Документы собраны в ${OUT_DIR}`);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
